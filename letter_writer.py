"""Обращение к Anthropic API: получить ТОЛЬКО тело ответа официально-деловым стилем.

Модель не пишет обращение, шапку, подпись и «исп.» — всё это уже есть в бланке.
Возвращаем список абзацев (строк), которые бот вставит в шаблон.
"""

import os
import anthropic

MODEL = "claude-sonnet-5"

SYSTEM_PROMPT = (
    "Ты — помощник по деловой переписке в строительной организации. "
    "Твоя задача — написать ТОЛЬКО ТЕЛО ответного письма на русском языке, "
    "официально-деловым стилем.\n\n"
    "Строгие правила:\n"
    "1. НЕ пиши обращение («Уважаемый…»), шапку, дату, адресата, подпись и «исп.» — "
    "всё это уже есть в бланке письма.\n"
    "2. НЕ пиши вводный абзац о том, кто является Подрядчиком/исполнителем — он тоже уже в бланке. "
    "Начинай сразу с сути ответа.\n"
    "3. Ничего не выдумывай: не придумывай факты, цифры, даты, номера, суммы, которых нет во входящем письме "
    "или в тезисах. Если какого-то факта не хватает, вставь в тексте пометку [уточнить].\n"
    "4. Пиши по существу входящего письма, вежливо и корректно.\n"
    "5. Раздели ответ на абзацы, если это уместно. Между абзацами — пустая строка.\n"
    "6. Выдай только сам текст тела ответа, без каких-либо пояснений от себя."
)


def _client() -> anthropic.Anthropic:
    # Ключ берётся из переменной окружения ANTHROPIC_API_KEY.
    return anthropic.Anthropic()


def generate_body(incoming_text: str, theses: str, obj: dict) -> list[str]:
    """Сформировать тело ответа.

    incoming_text — текст входящего письма (пересланного боту).
    theses        — тезисы ответа от пользователя; если "—" (или пусто), отвечаем по смыслу входящего.
    obj           — запись объекта из config.OBJECTS (для контекста: организация, контракт).

    Возвращает список абзацев.
    """
    context_lines = [f"Объект: {obj['title']}.", f"Организация-адресат: {obj['company']}."]
    if obj.get("contract"):
        context_lines.append(f"Договор: {obj['contract']}.")
    context = " ".join(context_lines)

    theses = (theses or "").strip()
    if theses in ("", "-", "—", "–"):
        task = (
            "Тезисы ответа не заданы. Напиши тело ответа по смыслу входящего письма — "
            "корректно отреагируй на то, что в нём написано."
        )
    else:
        task = f"Тезисы ответа, которые нужно раскрыть в официальном стиле:\n{theses}"

    user_content = (
        f"{context}\n\n"
        f"ВХОДЯЩЕЕ ПИСЬМО:\n{incoming_text.strip()}\n\n"
        f"{task}"
    )

    response = _client().messages.create(
        model=MODEL,
        max_tokens=2000,
        thinking={"type": "disabled"},
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": user_content}],
    )

    # Собираем текст из всех текстовых блоков ответа.
    text = "".join(block.text for block in response.content if block.type == "text").strip()

    # Делим на абзацы: сначала по пустым строкам, иначе по одиночным переводам строк.
    if "\n\n" in text:
        paragraphs = [p.strip() for p in text.split("\n\n")]
    else:
        paragraphs = [p.strip() for p in text.split("\n")]

    return [p for p in paragraphs if p]
